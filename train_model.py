import os
import sys
import numpy as np
from scipy import stats
import psycopg2

# --- 接続設定（環境に合わせて修正） ---
DB_HOST = os.getenv("PGHOST", "192.168.0.9")
DB_PORT = int(os.getenv("PGPORT", "5432"))
DB_NAME = os.getenv("PGDATABASE", "iot_data")
DB_USER = os.getenv("PGUSER", "mqtt_user")
DB_PASS = os.getenv("PGPASSWORD", "mqtt_password")

OUTPUT_HEADER = "firmware/nano33_project/anomaly_model.h"

def fetch_normal_data():
    """PostgreSQL から直近 10 分間の平常データを取得"""
    print(f"Connecting to PostgreSQL at {DB_HOST}:{DB_PORT}...")
    conn = psycopg2.connect(
        host=DB_HOST, port=DB_PORT, dbname=DB_NAME, user=DB_USER, password=DB_PASS
    )
    query = """
    SELECT 
        (payload->>'rms_accel')::float AS accel,
        (payload->>'rms_sound')::float AS sound
    FROM telemetry
    WHERE created_at >= NOW() - INTERVAL '15 minutes'
    ORDER BY created_at ASC;
    """
    with conn.cursor() as cur:
        cur.execute(query)
        rows = cur.fetchall()
    conn.close()

    if len(rows) < 30:
        raise ValueError(f"学習データが少なすぎます（{len(rows)} 件）。平常時データを 2〜3 分間流してください。")
    
    return np.array(rows)

def train_and_export():
    try:
        # DB 接続またはローカル baseline.csv から読み込み
        if os.path.exists("baseline.csv"):
            print("Found baseline.csv, loading local dataset...")
            data = np.loadtxt("baseline.csv", delimiter=",", skiprows=1)
        else:
            data = fetch_normal_data()
    except Exception as e:
        print(f"PostgreSQL fetch failed ({e}). Checking local fallback...")
        if os.path.exists("baseline.csv"):
            data = np.loadtxt("baseline.csv", delimiter=",", skiprows=1)
        else:
            print("Error: Could not retrieve training data.")
            sys.exit(1)

    print(f"Training on {len(data)} normal samples...")

    # 1. 平均ベクトルの計算
    mu = np.mean(data, axis=0)
    mu_accel = mu[0]
    mu_sound = mu[1]

    # 2. 共分散行列とその逆行列の計算
    cov = np.cov(data, rowvar=False)
    # 特異行列回避のための微小微加
    cov += np.eye(2) * 1e-6
    inv_cov = np.linalg.inv(cov)

    # 3. 閾値の設定（カイ二乗分布 自由度2、信頼区間 99% / 99.9%）
    threshold_99 = stats.chi2.ppf(0.99, df=2)
    threshold_999 = stats.chi2.ppf(0.999, df=2)

    print(f"Mean Accel : {mu_accel:.4f} G")
    print(f"Mean Sound : {mu_sound:.2f}")
    print(f"Threshold (Chi2 99%)  : {threshold_99:.2f}")
    print(f"Threshold (Chi2 99.9%): {threshold_999:.2f}")

    # 4. C言語ヘッダーファイルの自動生成
    header_content = f"""/* Auto-generated by train_model.py on Raspi 5 */
#ifndef ANOMALY_MODEL_H
#define ANOMALY_MODEL_H

#define MODEL_MU_ACCEL  {mu_accel:.6f}f
#define MODEL_MU_SOUND  {mu_sound:.6f}f

// 逆共分散行列 (2x2)
#define MODEL_INV_COV_00 {inv_cov[0, 0]:.6f}f
#define MODEL_INV_COV_01 {inv_cov[0, 1]:.6f}f
#define MODEL_INV_COV_10 {inv_cov[1, 0]:.6f}f
#define MODEL_INV_COV_11 {inv_cov[1, 1]:.6f}f

// マハラノビス距離二乗の閾値
#define THRESHOLD_ANOMALY {threshold_99:.4f}f

static inline float compute_mahalanobis_sq(float accel, float sound) {{
    float d0 = accel - MODEL_MU_ACCEL;
    float d1 = sound - MODEL_MU_SOUND;
    
    // D^2 = d^T * inv_cov * d
    float dist_sq = d0 * (MODEL_INV_COV_00 * d0 + MODEL_INV_COV_01 * d1)
                  + d1 * (MODEL_INV_COV_10 * d0 + MODEL_INV_COV_11 * d1);
    return dist_sq;
}}

#endif // ANOMALY_MODEL_H
"""

    os.makedirs(os.path.dirname(OUTPUT_HEADER), exist_ok=True)
    with open(OUTPUT_HEADER, "w") as f:
        f.write(header_content)

    print(f"Successfully generated header: {OUTPUT_HEADER}")

if __name__ == "__main__":
    train_and_export()
